namespace EvalToolkit.UI.Services;

/// <summary>
/// Centralised compile-time constants for the toast-notification COM
/// activator CLSID. The actual COM class registration lives in the
/// packaged-app manifest (<c>Package.appxmanifest</c>); the runtime
/// (<see cref="TrayIconService"/>) relies on the Windows App SDK to
/// auto-discover the activator from the manifest, so the CLSID is
/// not consumed by managed code today. We still publish it here so
/// the GUID is grep-able and any future P/Invoke-style activator
/// registration has one canonical reference.
/// </summary>
/// <remarks>
/// <para>
/// **DO NOT CHANGE THIS GUID.** It is the toast activator class
/// identifier baked into every shipped MSIX. Bumping it would orphan
/// every toast pinned in Action Center by prior versions of the app
/// (those toast payloads carry the old CLSID and the OS won't be able
/// to launch the new package to handle their click).
/// </para>
/// <para>
/// Generated by slice 33 (<c>msix-packaging</c>) via
/// <c>[guid]::NewGuid()</c>. Mirrored into
/// <c>Package.appxmanifest</c> under <c>com:Class Id</c> and
/// <c>desktop:ToastNotificationActivation ToastActivatorCLSID</c>.
/// </para>
/// </remarks>
internal static class NotificationActivatorIds
{
    /// <summary>
    /// Stable CLSID for the <c>EvalToolkit Toast Activator</c> COM
    /// class declared in <c>Package.appxmanifest</c>. Format is
    /// upper-case hyphenated (manifest convention); P/Invoke callers
    /// that need a <see cref="System.Guid"/> can wrap with
    /// <c>new Guid(NotificationActivatorIds.ToastActivatorClsid)</c>.
    /// </summary>
    public const string ToastActivatorClsid = "15FDE3FE-65CF-4E3D-8B0B-3C4B8B1BD68F";
}
