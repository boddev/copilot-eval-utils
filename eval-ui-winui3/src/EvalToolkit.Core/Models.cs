namespace EvalToolkit.Core;

/// <summary>
/// A single generated evaluation item. Mirrors the TS
/// <c>GeneratedEvalItem</c> interface in <c>eval-gen/src/types.ts</c>.
/// Property names in this record use C# casing; the JSON writer maps
/// them to the snake_case wire shape the existing artifacts use.
/// </summary>
public sealed record GeneratedEvalItem
{
    /// <summary>Stable identifier for matching across tools.</summary>
    public required string Id { get; init; }

    public required string Prompt { get; init; }
    public required string ExpectedAnswer { get; init; }
    public required string SourceLocation { get; init; }
    public required IReadOnlyList<Assertion> Assertions { get; init; }
    public required QuestionCategory Category { get; init; }
    public required Difficulty Difficulty { get; init; }
    public required IReadOnlyList<string> SupportingFacts { get; init; }
    public required GroundingConfidence GroundingConfidence { get; init; }

    /// <summary>
    /// All distinct row references the question grounds in (primary + supporting).
    /// Used for coverage. Optional — matches the TS field's optionality.
    /// </summary>
    public IReadOnlyList<string>? ReferencedRows { get; init; }
}

/// <summary>
/// Complete generated evaluation set. Mirrors the TS <c>EvalSet</c>
/// interface; the writer emits this with snake_case keys and the
/// <c>schemaVersion</c> string fixed at <c>"1.4.0"</c> for m365 docs
/// (see <see cref="M365EvalDocument"/>).
/// </summary>
public sealed record EvalSet
{
    public required string Version { get; init; }
    public required DateTimeOffset GeneratedAt { get; init; }
    public required string Description { get; init; }
    public required string SourceFile { get; init; }
    public required int ItemCount { get; init; }
    public required IReadOnlyList<GeneratedEvalItem> Items { get; init; }

    /// <summary>Connector diagnostics warnings (if schema was provided).</summary>
    public IReadOnlyList<string>? Warnings { get; init; }

    /// <summary>Generation metadata for reproducibility.</summary>
    public EvalSetMetadata? Metadata { get; init; }
}

/// <summary>Generation-time metadata embedded in <see cref="EvalSet"/>.</summary>
public sealed record EvalSetMetadata
{
    public required string Model { get; init; }
    public string? SourceHash { get; init; }
    public required string EvalgenVersion { get; init; }
    public IReadOnlyList<string>? AvoidanceEvalsets { get; init; }
    public int? AvoidanceItemsCompared { get; init; }
    public int? CrossRunDuplicatesRemoved { get; init; }
    public int? CrossRunAssertionOverlaps { get; init; }
}

/// <summary>
/// EvalGen metadata stored in m365 eval-document extensions. Mirrors the
/// TS <c>EvalGenM365Extension</c> interface. All fields optional because
/// it gets merged into existing documents.
/// </summary>
public sealed record EvalGenM365Extension
{
    public string? ItemId { get; init; }
    public string? SourceLocation { get; init; }
    public IReadOnlyList<Assertion>? Assertions { get; init; }
    public QuestionCategory? Category { get; init; }
    public Difficulty? Difficulty { get; init; }
    public IReadOnlyList<string>? SupportingFacts { get; init; }
    public GroundingConfidence? GroundingConfidence { get; init; }
    public IReadOnlyList<string>? ReferencedRows { get; init; }
    public bool? SyntheticThread { get; init; }
    public bool? ConversationChaining { get; init; }

    /// <summary>One of the values supported by the TS field; only "sequential_chunk" is currently emitted.</summary>
    public string? Grouping { get; init; }

    public int? PromptsPerThread { get; init; }
    public string? ThreadId { get; init; }
}

/// <summary>A single m365/evalscore JSON turn generated by EvalGen.</summary>
public sealed record M365EvalTurn
{
    public required string Prompt { get; init; }
    public string? ExpectedResponse { get; init; }
    public string? Context { get; init; }
    public M365TurnExtensions? Extensions { get; init; }
}

public sealed record M365TurnExtensions
{
    public EvalGenM365Extension? Evalgen { get; init; }
}

/// <summary>A multi-prompt item in the m365/evalscore JSON document.</summary>
public sealed record M365EvalItem
{
    public required string Name { get; init; }
    public string? Description { get; init; }
    public required IReadOnlyList<M365EvalTurn> Turns { get; init; }
    public M365TurnExtensions? Extensions { get; init; }
}

/// <summary>m365/evalscore-compatible JSON document for multi-prompt evaluators.</summary>
public sealed record M365EvalDocument
{
    /// <summary>Fixed at <c>"1.4.0"</c> to match the TS schema string.</summary>
    public string SchemaVersion { get; init; } = "1.4.0";

    public required IReadOnlyDictionary<string, object?> Metadata { get; init; }
    public required IReadOnlyList<M365EvalItem> Items { get; init; }
}

/// <summary>
/// Validation result for a generated eval set. Mirrors the TS
/// <c>ValidationResult</c> interface.
/// </summary>
public sealed record ValidationResult
{
    public required bool Passed { get; init; }
    public required int TotalItems { get; init; }
    public required int DuplicatesRemoved { get; init; }
    public required IReadOnlyDictionary<QuestionCategory, int> CategoryBalance { get; init; }
    public required double CoverageScore { get; init; }
    public required IReadOnlyList<string> Issues { get; init; }
    public int? UniqueRowsReferenced { get; init; }
    public int? TotalRows { get; init; }
    public double? RealisticMaxCoverage { get; init; }
    public int? RecommendedCountForTarget { get; init; }
    public bool? DatasetSampledNotExhaustive { get; init; }
}

/// <summary>
/// LLM-generated question intent (intermediate pipeline stage). Mirrors
/// the TS <c>QuestionIntent</c> interface.
/// </summary>
public sealed record QuestionIntent
{
    public required string Intent { get; init; }
    public required QuestionCategory Category { get; init; }
    public required Difficulty Difficulty { get; init; }
    public required IReadOnlyList<string> TargetFields { get; init; }
    public required IReadOnlyList<string> TargetRowReferences { get; init; }

    /// <summary>Pre-assigned primary row reference (set by orchestrator before LLM draft).</summary>
    public string? AssignedPrimaryRow { get; init; }
}

/// <summary>
/// LLM-generated question with grounding info. Mirrors the TS
/// <c>DraftedQuestion</c> interface.
/// </summary>
public sealed record DraftedQuestion
{
    public required string Prompt { get; init; }
    public required QuestionCategory Category { get; init; }
    public required Difficulty Difficulty { get; init; }
    public required IReadOnlyList<Fact> ReferencedFacts { get; init; }
    public required string ExpectedAnswer { get; init; }
    public required IReadOnlyList<string> SupportingFacts { get; init; }
    public required string SourceLocation { get; init; }

    /// <summary>Fact IDs the LLM cited as evidence (preferred; null if model didn't return them).</summary>
    public IReadOnlyList<string>? SupportingFactIds { get; init; }

    /// <summary>Distinct row references actually used (resolved from <see cref="SupportingFactIds"/> or back-matched).</summary>
    public IReadOnlyList<string>? ReferencedRows { get; init; }

    /// <summary>Pre-assigned primary row reference (carried from intent).</summary>
    public string? AssignedPrimaryRow { get; init; }
}
